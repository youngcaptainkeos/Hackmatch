// Optional native development services. No Docker; never touches system MySQL.
import { MongoMemoryServer } from 'mongodb-memory-server';
import { mkdir, writeFile, readFile, access, chmod } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { randomBytes, createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { tmpdir } from 'node:os';
import mysql from 'mysql2/promise';
const projectKey = createHash('sha256').update(resolve('.')).digest('hex').slice(0, 10);
const root = resolve(tmpdir(), `hackmatch-native-${projectKey}`);
await mkdir(root, { recursive: true, mode: 0o700 });
await chmod(root, 0o700);
const dataDirectory = resolve(root, 'mysql');
await mkdir(dataDirectory, { recursive: true });
const suffix = createHash('sha256').update(root).digest('hex').slice(0, 10);
const socket = `/tmp/hackmatch-${suffix}.sock`;
let server, mongo;
function run(args) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.env.MYSQLD_PATH || 'mysqld', args, {
      stdio: ['ignore', 'ignore', 'pipe'],
    });
    let message = '';
    child.stderr.on('data', (data) => (message += data));
    child.on('error', reject);
    child.on('exit', (code) =>
      code === 0
        ? resolve()
        : reject(
            new Error(
              `mysqld setup failed (${code}). Check .local-data/mysql-setup.log. ${message.slice(0, 150)}`
            )
          )
    );
  });
}
try {
  try {
    await access(resolve(dataDirectory, 'auto.cnf'));
  } catch {
    await run([
      '--no-defaults',
      '--initialize-insecure',
      `--datadir=${dataDirectory}`,
      '--innodb-buffer-pool-size=64M',
      `--log-error=${resolve(root, 'mysql-setup.log')}`,
    ]);
  }
  let existingServer;
  try {
    existingServer = await mysql.createConnection({ user: 'root', socketPath: socket });
  } catch {
    /* Our private socket is not running yet. */
  }
  if (existingServer) {
    await existingServer.end();
    console.log('Reusing this project’s isolated native MySQL server.');
  } else {
    server = spawn(
      process.env.MYSQLD_PATH || 'mysqld',
      [
        '--no-defaults',
        `--datadir=${dataDirectory}`,
        `--socket=${socket}`,
        `--pid-file=${resolve(root, 'mysql.pid')}`,
        '--skip-networking',
        '--mysqlx=OFF',
        '--innodb-buffer-pool-size=64M',
        `--log-error=${resolve(root, 'mysql.log')}`,
      ],
      { stdio: 'ignore' }
    );
    server.on('error', () =>
      console.error('Cannot start mysqld. Set MYSQLD_PATH to your installed MySQL server binary.')
    );
  }
  let db;
  for (let attempt = 0; attempt < 60; attempt++) {
    try {
      db = await mysql.createConnection({ user: 'root', socketPath: socket });
      break;
    } catch {
      await new Promise((resolve) => setTimeout(resolve, 500));
    }
  }
  if (!db) throw new Error('Native MySQL did not start. See the MySQL log in ${root}.');
  await db.query('CREATE DATABASE IF NOT EXISTS hackmatch');
  await db.end();
  await mkdir(resolve(root, 'mongo'), { recursive: true });
  mongo = await MongoMemoryServer.create({
    instance: {
      port: 27018,
      dbPath: resolve(root, 'mongo'),
      storageEngine: 'wiredTiger',
      ip: '127.0.0.1',
    },
    binary: { version: '7.0.24' },
  });
  let existing = '';
  try {
    existing = await readFile('.env.local', 'utf8');
  } catch {}
  if (existing && !existing.startsWith('# Generated by HackMatch native development services'))
    throw new Error(
      'Existing .env.local is preserved. Set MYSQL_SOCKET to the private socket shown in .local-data/mysql.log and use mongodb://127.0.0.1:27018, or move your existing .env.local aside before rerunning.'
    );
  const seedPassword =
    existing.match(/^SEED_PASSWORD=(.*)$/m)?.[1] || randomBytes(18).toString('hex');
  await writeFile(
    '.env.local',
    `# Generated by HackMatch native development services\nMYSQL_URL=mysql://root@localhost/hackmatch\nMYSQL_SOCKET=${socket}\nMYSQL_SSL=false\nMONGODB_URI=mongodb://127.0.0.1:27018\nMONGODB_DATABASE=hackmatch\nAPP_ORIGIN=http://localhost:3000\nSEED_PASSWORD=${seedPassword}\n`,
    { mode: 0o600 }
  );
  console.log(`Local database files: ${root}`);
  console.log('Native MySQL and MongoDB are ready. .env.local configured (secrets not printed).');
  console.log(
    'Keep this terminal open. In another terminal: npm run db:init, npm run db:seed, npm run dev.'
  );
  console.log(
    'Seed account password is stored locally in .env.local. These isolated services are for local development only.'
  );
} catch (error) {
  console.error(error.message);
  if (mongo) await mongo.stop();
  if (server) server.kill('SIGTERM');
  process.exit(1);
}
let closing = false;
async function stop() {
  if (closing) return;
  closing = true;
  console.log('Stopping only HackMatch native development services…');
  await mongo?.stop();
  server?.kill('SIGTERM');
  process.exit(0);
}
process.on('SIGINT', stop);
process.on('SIGTERM', stop);
await new Promise(() => {});
